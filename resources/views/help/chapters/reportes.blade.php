<p class="cap-intro">Para controlar el dinero y el negocio: qué entró y salió de las cajas, los cierres de caja y los reportes de préstamos, pagos, clientes y almacenes, con exportación a PDF y Excel.</p>

<h3>Movimientos de caja</h3>
<ol class="pasos">
    <li>Menú <span class="menu">Movimientos</span>.</li>
    <li>Arriba verás los <strong>ingresos</strong>, los <strong>egresos</strong> y la <strong>utilidad operativa</strong> del periodo filtrado.</li>
    <li>Filtra por caja, tipo (ingreso o egreso), categoría (desembolso, pago de interés, multa, amortización, liquidación, compra, venta, gastos, ajustes, reversiones…), fechas o busca por texto.</li>
    <li>Cada movimiento muestra fecha, descripción, monto y quién lo registró.</li>
</ol>

<h3>Cierres de caja y descuadres</h3>
<p>En <span class="menu">Movimientos</span>, sección <span class="boton">Cierres de Caja</span>, cada sesión de caja muestra: quién abrió y cerró, monto de apertura, ingresos, egresos, el monto <strong>esperado</strong>, el <strong>declarado</strong> al cerrar y el <strong>descuadre</strong> (la diferencia).</p>
<p>Si un cierre tiene descuadre, se puede corregir con <span class="boton">Ajuste de cierre</span>:</p>
<ul>
    <li><span class="boton">Corregir conteo</span>: si te equivocaste al contar o al escribir el monto de cierre. Escribes el monto correcto y el descuadre se recalcula.</li>
    <li><span class="boton">Registrar ajuste</span>: si la diferencia es <strong>real</strong> (faltó o sobró dinero). Se registra un movimiento de caja que deja el cierre cuadrado. Escribe el motivo (por ejemplo "faltante de caja no justificado").</li>
</ul>

<h3>Centro de reportes</h3>
<p>Menú <span class="menu">Reportes</span>: muestra un resumen (préstamos, activos, clientes, en mora, total desembolsado, recaudado y por cobrar) y los reportes disponibles:</p>
<table class="tabla">
    <tr><th>Reporte</th><th>Para qué sirve</th></tr>
    <tr><td><strong>Movimientos</strong></td><td>Ingresos, egresos y cierres de caja (el mismo módulo de arriba).</td></tr>
    <tr><td><strong>Préstamos</strong></td><td>La cartera completa por estado, sucursal, producto y fechas, con montos, pagos y saldos.</td></tr>
    <tr><td><strong>Pagos</strong></td><td>Todos los cobros recibidos por fecha y método de pago, con el desglose de capital e intereses.</td></tr>
    <tr><td><strong>Cartera de clientes</strong></td><td>Clientes con préstamos activos: total prestado, pagado y pendiente por cliente.</td></tr>
    <tr><td><strong>Almacenes</strong></td><td>Productos en custodia por almacén: retenidos, en mora y disponibles para venta.</td></tr>
</table>

<h3>Exportar a PDF o Excel</h3>
<ol class="pasos">
    <li>Aplica los filtros que necesites.</li>
    <li>Presiona el botón de exportar (<span class="boton">PDF</span> o <span class="boton">Excel</span>).</li>
    <li>Elige <strong>Resumen</strong> o <strong>Detallado</strong>. El archivo sale con los filtros aplicados.</li>
</ol>
<ul>
    <li><strong>PDF:</strong> se abre una página lista para imprimir; para guardarla como archivo elige <em>Guardar como PDF</em> en la ventana de impresión.</li>
    <li><strong>Excel:</strong> descarga un archivo <em>.xlsx</em>; los montos quedan como números, para poder sumarlos o filtrarlos.</li>
</ul>
<p>Se puede exportar desde Movimientos, los reportes de Préstamos, Pagos, Clientes y Almacenes, y las listas de Préstamos y Clientes.</p>

<h3>Reportes en la app móvil</h3>
<ol class="pasos">
    <li>Menú lateral › <span class="menu">Reportes</span>: arriba está el resumen general.</li>
    <li>Toca un reporte (Préstamos, Pagos, Movimientos de caja, Cierres de caja, Cartera de clientes o Almacenes).</li>
    <li>Usa el buscador y el botón de <strong>filtros</strong> (fechas, con atajos <em>Hoy</em>, <em>Esta semana</em>, <em>Este mes</em>; estado, sucursal, caja…).</li>
    <li><strong>Toca una fila para ver su detalle:</strong> un préstamo abre su ficha; un pago, su detalle con el recibo; un movimiento de caja muestra sus datos y el botón para ir al préstamo, la venta o la compra que lo originó; un <strong>cierre de caja</strong> muestra el resumen (apertura, ingresos, egresos, esperado, contado y descuadre) y <strong>todos los movimientos de esa sesión</strong>; un cliente abre su ficha.</li>
    <li>Con el botón de <strong>descarga</strong> eliges <em>PDF</em> o <em>Excel</em>, resumen o detallado. Cuando está listo, puedes <span class="boton">Abrir</span> el archivo o <span class="boton">Compartir</span>lo por WhatsApp, correo, etc.</li>
</ol>
<div class="nota"><strong>Nota:</strong> los números son los mismos que en la web. Un PDF muy grande (más de 2.000 filas) no se genera: filtra por fechas o descárgalo en Excel.</div>

<p class="cap-intro">Respuestas rápidas a las dudas y mensajes más comunes.</p>

<h3>"No hay ninguna caja abierta…" / el botón Nuevo Préstamo tiene candado</h3>
<p>Abre tu caja con <span class="boton">Aperturar caja</span> (barra superior). Si no aparece el botón, no tienes una caja asignada: pide al administrador que te asigne una en <span class="menu">Cajas</span>.</p>

<h3>"No tienes una caja asignada" o "Tu usuario no tiene un personal asociado"</h3>
<p>Tu usuario no está vinculado a un empleado de <span class="menu">Personal</span> o ese empleado no tiene caja. Lo corrige el administrador.</p>

<h3>No puedo registrar un préstamo, una compra o un gasto por el monto</h3>
<p>El monto supera el <strong>saldo disponible</strong> de tu caja. Revisa el saldo; si hace falta más efectivo, consulta con el Gerente.</p>

<h3>"Debes pagar primero el interés pendiente más antiguo"</h3>
<p>Los intereses se cobran en orden. Cobra primero el periodo pendiente más antiguo (puede ser un pago parcial).</p>

<h3>No puedo editar un préstamo</h3>
<p>Solo se editan préstamos abiertos que todavía no tienen pagos, intereses pagados ni amortizaciones. Pasa el mouse sobre el botón con candado para ver el motivo exacto.</p>

<h3>No puedo eliminar un préstamo, una compra o una venta</h3>
<ul>
    <li><strong>Préstamo:</strong> no se elimina si tiene intereses pagados o cobros en caja.</li>
    <li><strong>Compra:</strong> no se elimina si el producto ya salió del inventario (vendido o retirado).</li>
    <li><strong>Venta:</strong> requiere permiso, o una autorización de alguien con permiso (válida 24 horas y solo para esa venta).</li>
</ul>

<h3>El préstamo dice "solo lectura"</h3>
<p>Está <strong>finalizado</strong> (ya se liquidó), <strong>incumplido</strong> (venció la gracia y la prenda pasó a venta) o <strong>eliminado</strong>. Solo se puede consultar e imprimir.</p>

<h3>El cliente pagó la multa pero sigue en mora</h3>
<p>Es normal: la multa es aparte. Para salir de la mora debe pagar los intereses vencidos o liquidar el préstamo.</p>

<h3>Al cerrar la caja hay diferencia</h3>
<p>Antes de cerrar, revisa los movimientos del día en <span class="menu">Movimientos</span>. Si ya cerraste, un Gerente puede usar <span class="boton">Ajuste de cierre</span>: <em>Corregir conteo</em> si fue un error al contar, o <em>Registrar ajuste</em> si realmente faltó o sobró dinero.</p>

<h3>No veo un menú o un botón que otro compañero sí ve</h3>
<p>Depende de los permisos de tu cargo. Pide al administrador que revise el rol de tu cargo en <span class="menu">Cargos</span>.</p>

<h3>Me equivoqué de cliente o de datos en una venta o compra</h3>
<p>Elimina la operación (el dinero y el producto vuelven a su lugar) y regístrala de nuevo con los datos correctos.</p>

<h3>Olvidé mi contraseña</h3>
<p>Pide al administrador que te asigne una nueva desde <span class="menu">Personal</span>; luego cámbiala en <span class="boton">Mi Perfil</span>.</p>

<p class="cap-intro">Un catálogo es una página con fotos y datos de productos a la venta, que se comparte con los clientes por un <strong>enlace</strong> (por ejemplo por WhatsApp) o en <strong>PDF</strong>. El cliente no necesita usuario para verlo.</p>

<h3>Crear un catálogo</h3>
<ol class="pasos">
    <li>Menú <span class="menu">Catálogos</span> › <span class="boton">Nuevo catálogo</span>.</li>
    <li><strong>Sucursal:</strong> la tuya o todas las sucursales (según tu cargo).</li>
    <li><strong>Configuración:</strong> título, descripción, color y logo; si se muestran los <strong>precios</strong> y el <strong>contacto</strong> (teléfono, WhatsApp, email).</li>
    <li><strong>Disponible hasta</strong> (opcional): fecha en que el enlace deja de funcionar. Vacío = no vence.</li>
    <li><strong>Productos disponibles para la venta:</strong> filtra por categoría u origen (de préstamo, de compra, otros) y agrega los productos uno por uno o con <span class="boton">Agregar todos</span>. Arrastra los productos para ordenarlos.</li>
    <li>Revisa la <strong>vista previa</strong> (así lo verá el cliente) y guarda.</li>
</ol>

<h3>Compartir el catálogo</h3>
<ul>
    <li>En el detalle del catálogo, <strong>Enlace público</strong> › <span class="boton">Copiar</span> y pégalo en WhatsApp, Facebook, etc.</li>
    <li><span class="boton">Exportar PDF</span> descarga el catálogo en PDF, <strong>con las fotos</strong> de los productos, para enviarlo o imprimirlo.</li>
    <li><span class="boton">Regenerar enlace</span> crea un enlace nuevo; el anterior deja de funcionar (útil si se compartió por error).</li>
</ul>

<h3>Estados del catálogo</h3>
<ul>
    <li><strong>Activo:</strong> el enlace funciona.</li>
    <li><strong>Pausado:</strong> desactivado manualmente al editarlo; el enlace deja de funcionar hasta que se vuelva a activar.</li>
    <li><strong>Vencido:</strong> pasó la fecha "Disponible hasta"; el enlace deja de funcionar.</li>
</ul>
<h3>Catálogos desde la app móvil</h3>
<ol class="pasos">
    <li>Menú lateral › <span class="menu">Catálogos</span> › <span class="boton">Nuevo catálogo</span>.</li>
    <li>Completa el título, la sucursal, el color, si muestra precios, el contacto y, si quieres, la fecha de vencimiento y el logo.</li>
    <li><span class="boton">Elegir productos</span>: busca o filtra por categoría y marca los productos (o <em>Seleccionar los visibles</em>). Mantén presionado un producto para cambiar el orden; tócalo para ponerle un nombre o un precio propio.</li>
    <li><span class="boton">Crear catálogo</span>. En el detalle: <span class="boton">Compartir</span> el enlace (WhatsApp, etc.), copiarlo, abrirlo o descargar el <span class="boton">PDF con fotos</span>.</li>
    <li>En el menú de los tres puntos: pausar o activar el enlace, generar un enlace nuevo o eliminar el catálogo.</li>
</ol>

<div class="aviso"><strong>Importante:</strong> el catálogo no quita solo los productos vendidos. Cuando vendas un producto del catálogo, quítalo con <span class="boton">Editar</span> para no ofrecer algo que ya no está.</div>

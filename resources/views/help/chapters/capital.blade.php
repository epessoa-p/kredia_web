<p class="cap-intro">Registro del dinero que el propietario <strong>aporta</strong> al negocio o <strong>retira</strong> de él. Permite saber el capital neto invertido.</p>

<h3>Registrar un aporte o un retiro</h3>
<ol class="pasos">
    <li>Menú <span class="menu">Capital</span> › <span class="boton">Registrar movimiento</span>.</li>
    <li>Elige el <strong>tipo de movimiento</strong>: <em>Aporte</em> (ingreso de capital) o <em>Retiro</em> (salida de capital).</li>
    <li>Escribe el <strong>monto</strong> (sin decimales), la fecha (hoy o anterior) y una descripción (opcional) y guarda.</li>
</ol>

<h3>Consultar el capital</h3>
<p>La pantalla muestra el <strong>total de aportes</strong>, el <strong>total de retiros</strong> y el <strong>capital neto</strong>, y el historial de movimientos con quién los registró. Un movimiento registrado por error se puede eliminar desde el historial.</p>
<div class="nota"><strong>Nota:</strong> el capital es un registro del propietario; no mueve dinero de las cajas. Para poner o sacar efectivo de una caja se usa la apertura, los gastos o los ajustes de caja.</div>

<p class="cap-intro">Se venden los productos del almacén: prendas de préstamos incumplidos, productos comprados y otros ingresos de stock. La venta puede ser al <strong>contado</strong> o a <strong>crédito</strong> (en cuotas).</p>

<div class="aviso"><strong>Recuerda:</strong> para vender necesitas una <strong>caja abierta</strong>. Solo se venden productos del almacén de la sucursal de tu caja; los de otras sucursales se muestran como referencia.</div>

<h3>Registrar una venta</h3>
<ol class="pasos">
    <li>Menú <span class="menu">Ventas</span> › <span class="boton">Nueva Venta</span>.</li>
    <li><strong>Comprador</strong> (opcional): <em>Existente</em> para buscarlo, o <em>Nuevo</em> para registrar sus datos (nombre, CI/NIT, teléfono, email, dirección).</li>
    <li><strong>Sucursal</strong> y <strong>producto disponible</strong>. Con <span class="boton">Ver productos con detalle</span> ves un catálogo con fotos, datos y stock para elegir.</li>
    <li><strong>Precio de venta</strong>: el sistema muestra el costo original y la <strong>ganancia estimada</strong>.</li>
    <li><strong>Tipo de venta</strong>: <em>Contado</em> o <em>Crédito</em> (ver abajo).</li>
    <li>Opcional: notas y fotos.</li>
    <li>Presiona <span class="boton">Registrar venta</span>. Se genera el código <strong>VE-00001</strong>, el producto sale del almacén y el cobro entra a la caja.</li>
    <li>Imprime el recibo (<span class="boton">Imprimir ahora</span>, 80 mm térmico). Se puede reimprimir en cualquier momento desde el detalle.</li>
</ol>

<h3>Venta a crédito (en cuotas)</h3>
<ol class="pasos">
    <li>En <strong>Tipo de venta</strong> elige <em>Crédito</em>.</li>
    <li><strong>Porcentaje adicional de crédito</strong>: el recargo por vender a crédito, sobre el precio de venta. El sistema calcula el monto adicional y el <strong>total financiado</strong>.</li>
    <li><strong>Cuota inicial</strong>: lo que el cliente paga hoy al contado. Se resta del total financiado.</li>
    <li>Arma el plan con <span class="boton">Agregar cuota</span>: fecha de cada cuota y su valor (por porcentaje o por monto). Las cuotas deben cubrir el <strong>saldo en cuotas</strong>; el resumen indica si el plan está completo.</li>
    <li>Registra la venta. La cuota inicial entra a la caja hoy; las demás quedan pendientes.</li>
</ol>

<h3>Cobrar una cuota</h3>
<ol class="pasos">
    <li>Abre la venta (menú <span class="menu">Ventas</span>, o desde la ficha del cliente).</li>
    <li>En el plan de cuotas, en la cuota que corresponde, presiona <span class="boton">Pagar</span>.</li>
    <li>Revisa el monto, la fecha y escribe notas si quieres. Presiona <span class="boton">Confirmar pago</span>.</li>
</ol>
<div class="nota"><strong>Nota:</strong> las cuotas vencidas se marcan como <em>Vencida hace…</em>. Una cuota ya pagada no se puede cobrar dos veces.</div>

<h3>Cancelación anticipada (liquidar la venta)</h3>
<p>Si el cliente quiere pagar todo lo que debe:</p>
<ol class="pasos">
    <li>En el detalle de la venta presiona <span class="boton">Liquidar · monto</span>.</li>
    <li>Revisa el detalle por cuota. Las cuotas <strong>futuras no generan interés</strong>; solo se cobra interés sobre las vencidas o que vencen hoy.</li>
    <li>Confirma. Todas las cuotas quedan pagadas.</li>
</ol>

<h3>Venta rápida</h3>
<p>Botón <span class="boton">Venta rápida</span> en la barra superior: muestra los productos disponibles de tu sucursal con foto, categoría, stock y precio sugerido. Al elegir uno se abre la venta con la sucursal y el producto ya cargados.</p>

<h3>Eliminar (devolver) una venta</h3>
<ol class="pasos">
    <li>En la lista de ventas o en el detalle, usa la opción de eliminar.</li>
    <li>Pestaña <span class="boton">Eliminar yo mismo</span>: elige el <strong>motivo</strong> (producto defectuoso, error en el registro, cliente arrepentido, producto incorrecto u otro), escribe observaciones y presiona <span class="boton">Confirmar eliminación</span>.</li>
</ol>
<p>El producto <strong>vuelve al inventario</strong> y se registra un <strong>egreso en caja</strong> por lo cobrado. En ventas a crédito solo se devuelven las cuotas ya cobradas; las pendientes se anulan.</p>
<div class="aviso"><strong>Autorizar a otro:</strong> si tienes permiso de eliminar ventas, en la pestaña <span class="boton">Autorizar a otro</span> puedes permitir que otra persona elimine <strong>solo esa venta, una única vez</strong>. La autorización vence en <strong>24 horas</strong> (<span class="boton">Autorizar por 24 horas</span>).</div>

<h3>Buscar ventas</h3>
<p>En <span class="menu">Ventas</span> filtra por estado (completada, cancelada), personal, fechas y sucursal. Cada venta muestra si fue al contado o a crédito y cuánto está pagado.</p>

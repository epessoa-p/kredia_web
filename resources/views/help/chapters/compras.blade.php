<p class="cap-intro">Una compra registra un producto que el negocio compra a una persona. El dinero sale de la caja y el producto entra al almacén para venderlo después.</p>

<h3>Registrar una compra</h3>
<ol class="pasos">
    <li>Abre la caja (el monto de la compra sale de ella). Arriba del formulario verás el <strong>saldo disponible</strong>.</li>
    <li>Menú <span class="menu">Compras</span> › <span class="boton">Nueva Compra</span>.</li>
    <li><strong>Vendedor / Cliente</strong>: <em>Existente</em> para buscarlo o <em>Nuevo</em> para registrar sus datos (nombre, CI/NIT, teléfono, email, dirección).</li>
    <li><strong>Sucursal y categoría</strong>: elige la categoría del producto; el formulario muestra los datos que corresponden:
        <ul>
            <li><strong>Vehículo:</strong> marca, modelo (año), placa, chasis y detalles.</li>
            <li><strong>Joyas:</strong> tipo de joya, kilataje, tipo de material y detalles.</li>
            <li><strong>Garrafas:</strong> detalles.</li>
            <li><strong>Otros artículos:</strong> nombre, marca, modelo, serial y detalles.</li>
        </ul>
    </li>
    <li>Opcional: <strong>precio referencial</strong> (precio de venta sugerido) y <strong>fotos</strong> (<span class="boton">Subir archivos</span> o <span class="boton">Usar cámara</span>; JPG, PNG o WebP de hasta 5 MB).</li>
    <li><strong>Monto de compra</strong>: lo que se paga al vendedor. Si supera el saldo de la caja, aparece el aviso y no se puede guardar.</li>
    <li>Presiona <span class="boton">Registrar compra</span>. Se genera el código <strong>CO-00001</strong>.</li>
</ol>

<h3>Imprimir el documento de compra</h3>
<p>En el detalle de la compra:</p>
<ul>
    <li><span class="boton">Imprimir ticket</span>: comprobante corto (80 mm, térmico).</li>
    <li><span class="boton">Imprimir Documento</span>: el <strong>documento privado de compra</strong> (contrato legal) con los datos del vendedor y del producto, para que firme.</li>
</ul>

<h3>Eliminar una compra</h3>
<ol class="pasos">
    <li>En el detalle de la compra presiona <span class="boton">Eliminar compra</span> (requiere permiso) y confirma.</li>
    <li>El dinero <strong>vuelve a tu caja</strong> y el producto <strong>sale del inventario</strong>.</li>
</ol>
<div class="aviso"><strong>Atención:</strong> no se puede eliminar una compra cuyo producto ya se vendió, y necesitas una caja abierta para recibir la devolución del dinero. Si no se puede, el sistema muestra el motivo.</div>

<h3>Buscar compras</h3>
<p>En <span class="menu">Compras</span> filtra por sucursal, fechas o busca por cliente o producto. Abre una compra para ver su producto, vendedor, caja y fotos.</p>

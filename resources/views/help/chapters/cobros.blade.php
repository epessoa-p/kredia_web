<p class="cap-intro">Todos los cobros de un préstamo se hacen desde su <strong>detalle</strong>, en las pestañas <span class="boton">Interés</span>, <span class="boton">Amortizar</span>, <span class="boton">Liquidar</span> y <span class="boton">Multa</span>. El dinero entra a tu caja abierta.</p>

<div class="aviso"><strong>Recuerda:</strong> para cobrar necesitas una <strong>caja abierta</strong>. Cuando lo está, la sección muestra <em>"Caja activa: … Lista para cobrar"</em>. Los préstamos finalizados, incumplidos o eliminados no admiten cobros.</div>

<h3>Cobrar un interés</h3>
<ol class="pasos">
    <li>Busca el préstamo (menú <span class="menu">Préstamos</span>, o desde la ficha del cliente) y ábrelo.</li>
    <li>Ve a la pestaña <span class="boton">Interés</span>. En <strong>Periodos de interés</strong> verás cada periodo con su estado: <em>Pagado</em>, <em>Vencido</em>, <em>Pendiente</em> o <em>Eliminado</em>.</li>
    <li>En el periodo pendiente <strong>más antiguo</strong>, revisa el monto (ya viene con lo que falta pagar) y presiona <span class="boton">Pagar</span>.</li>
    <li>Imprime el recibo con <span class="boton">Imprimir ticket</span> (80 mm, térmico) si el cliente lo pide.</li>
</ol>
<div class="nota"><strong>Reglas:</strong>
    <ul>
        <li>Los intereses se pagan <strong>en orden</strong>: no se puede pagar un periodo si hay uno anterior pendiente.</li>
        <li>Se permite el <strong>pago parcial</strong>: escribe un monto menor y el periodo queda pendiente con el saldo restante.</li>
        <li>No se puede cobrar más de lo que falta del periodo.</li>
    </ul>
</div>

<h3>Amortizar capital</h3>
<p>El cliente devuelve una parte del capital, sin terminar el préstamo. Los intereses siguientes se calculan sobre el <strong>capital que queda</strong>, así que pagará menos interés.</p>
<ol class="pasos">
    <li>En el detalle, pestaña <span class="boton">Amortizar</span>.</li>
    <li>Escribe el <strong>monto a amortizar</strong> (mayor a 0 y no mayor al capital vigente), la fecha y notas si quieres.</li>
    <li>Presiona <span class="boton">Amortizar</span>. En <strong>Historial de amortizaciones</strong> verás el capital antes y después.</li>
</ol>

<h3>Liquidar el préstamo (el cliente recupera su prenda)</h3>
<ol class="pasos">
    <li>En el detalle, pestaña <span class="boton">Liquidar</span>. Se muestra el <strong>total para liquidar</strong>: capital vigente + intereses pendientes + multa pendiente (si la hay).</li>
    <li>Escribe el monto (debe ser <strong>al menos</strong> el total para liquidar), la fecha y notas si hace falta.</li>
    <li>Presiona <span class="boton">Liquidar préstamo</span> y confirma.</li>
</ol>
<p>El préstamo pasa a <strong>Finalizado</strong>, todos los intereses pendientes quedan pagados y la prenda queda <strong>liberada</strong> para devolverla al cliente. Imprime el recibo de liquidación.</p>
<div class="consejo"><strong>Consejo:</strong> entrega la prenda solo al titular, con su carnet de identidad, como dice el comprobante del préstamo.</div>

<h3>Cobrar la multa</h3>
<p>Si el préstamo está en mora, la pestaña <span class="boton">Multa</span> muestra la multa pendiente.</p>
<ol class="pasos">
    <li>Pestaña <span class="boton">Multa</span> › revisa el monto › <span class="boton">Pagar multa</span>.</li>
    <li>Una vez pagada, la multa ya no se cobra en la liquidación.</li>
</ol>
<div class="nota"><strong>Nota:</strong> pagar la multa no saca al préstamo de la mora: para eso hay que ponerse al día con los intereses vencidos. Ver el capítulo <em>Mora, multa e incumplimiento</em>.</div>

<h3>Eliminar o restaurar un periodo de interés</h3>
<p>Si un periodo de interés no corresponde (por ejemplo, por un acuerdo con el cliente), se puede eliminar:</p>
<ol class="pasos">
    <li>En <strong>Periodos de interés</strong>, en el periodo no pagado, presiona <span class="boton">Eliminar periodo</span> y confirma.</li>
    <li>El periodo queda marcado como <em>Eliminado</em>, con quién y cuándo lo eliminó.</li>
    <li>Para deshacerlo, usa <span class="boton">Restaurar</span> en ese periodo.</li>
</ol>
<div class="nota"><strong>Nota:</strong> no se pueden eliminar periodos ya pagados. Eliminar y restaurar requieren permisos específicos; solo se restaura en préstamos activos o en mora.</div>

<h3>Pagos de préstamos (lista)</h3>
<p>En el menú <span class="menu">Pagos préstamos</span> verás todos los pagos registrados (intereses, amortizaciones, multas y liquidaciones) con su fecha, tipo, monto y quién lo registró.</p>

<h3>Pagos en la app móvil</h3>
<ol class="pasos">
    <li>Menú lateral › <span class="menu">Pagos</span>: cada pago muestra el cliente, el préstamo, el tipo (Interés, Multa, Amortización o Liquidación), la <strong>sucursal con su color</strong>, quién lo cobró y la fecha. Arriba está el <strong>total</strong> de lo que se ve.</li>
    <li>Busca por cliente, código del préstamo (PR-00012) o referencia. Con el botón de <strong>filtros</strong> (arriba a la derecha) eliges fechas (<em>Hoy</em>, <em>Esta semana</em>, <em>Este mes</em>…), sucursal, tipo y método de pago.</li>
    <li>Toca un pago para ver el <strong>detalle</strong>: desglose, préstamo, cliente, caja y comprobante adjunto. Desde ahí, <span class="boton">Ver préstamo</span> o <span class="boton">Recibo PDF</span>.</li>
    <li><span class="boton">Recibo PDF</span>: elige <em>Ticket (80 mm)</em> para la impresora de tickets u <em>Hoja carta</em>. Cuando está listo, <span class="boton">Abrir</span> (para imprimir) o <span class="boton">Compartir</span> (WhatsApp, correo…).</li>
</ol>
<p>En el detalle de un préstamo, el <strong>Historial de pagos</strong> también se puede tocar para ver cada pago y su recibo.</p>

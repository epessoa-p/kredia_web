<p class="cap-intro">Cómo entrar al sistema, moverse por las pantallas y entender por qué cada persona ve opciones distintas.</p>

<h3>Ingresar al sistema</h3>
<ol class="pasos">
    <li>Abre el navegador (Chrome, Edge o Firefox) y entra a la dirección del sistema.</li>
    <li>Escribe tu <strong>usuario o correo</strong> y tu <strong>contraseña</strong> y presiona <span class="boton">Iniciar Sesión</span>. Marca <em>Recuerda mi información</em> solo en una computadora personal.</li>
    <li>Al entrar verás el <span class="menu">Dashboard</span> (pantalla de inicio).</li>
</ol>
<div class="nota"><strong>Nota:</strong> el usuario y la contraseña los crea el administrador al registrarte como personal. Si olvidaste la contraseña, pídele que la cambie.</div>

<h3>Partes de la pantalla</h3>
<ul>
    <li><strong>Menú lateral (izquierda):</strong> los módulos del sistema. Arriba muestra la empresa y tu sucursal (si trabajas en varias, la de tu caja abierta). El botón de las <strong>tres rayas</strong> de la barra superior oculta o muestra el menú para tener más espacio (el sistema lo recuerda); en el celular abre el menú.</li>
    <li><strong>Barra superior:</strong> los botones de caja (<span class="boton">Aperturar caja</span>, <span class="boton">Registrar gasto</span>, <span class="boton">Cerrar caja</span>), <span class="boton">Venta rápida</span> y el ícono de tu usuario (Mi perfil, Cerrar sesión).</li>
    <li><strong>Contenido:</strong> la pantalla del módulo que elegiste. Arriba se muestra el camino (por ejemplo <em>Préstamos › PR-00012</em>) para volver atrás.</li>
</ul>

<h3>El Dashboard</h3>
<p>Muestra un resumen del negocio. Según tu cargo verás:</p>
<ul>
    <li><strong>Encargados de tienda:</strong> los cobros de hoy, los de esta semana, los vencidos y los préstamos en mora, para saber a quién cobrar.</li>
    <li><strong>Gerentes y administradores:</strong> total de préstamos (activos, finalizados, vencidos), montos prestados, cobrados y por cobrar, valor del stock, capital y préstamos recientes.</li>
</ul>

<h3>Por qué no veo algunas opciones</h3>
<p>Lo que cada persona puede ver y hacer depende de los <strong>permisos de su cargo</strong>. Si no ves un menú o un botón está desactivado, es porque tu cargo no tiene ese permiso. Al pasar el mouse sobre un botón desactivado, muchas veces aparece el motivo.</p>
<ul>
    <li>El <strong>Gerente</strong> puede trabajar con todas las sucursales y elegir qué caja abrir.</li>
    <li>El resto del personal trabaja solo en <strong>su sucursal</strong> y con <strong>su caja</strong> asignada.</li>
</ul>
<div class="consejo"><strong>Consejo:</strong> si necesitas un permiso, pídeselo al administrador; se asigna al cargo en <span class="menu">Administración › Cargos</span> (ver el capítulo de Administración).</div>

<h3>Mayúsculas automáticas</h3>
<p>Los campos de texto de los formularios (nombres, direcciones, detalles) se escriben automáticamente en <strong>MAYÚSCULAS</strong>, para que todos los datos queden uniformes. Los correos y contraseñas no se cambian.</p>

<h3>Mi perfil y cambio de contraseña</h3>
<ol class="pasos">
    <li>Haz clic en el ícono de usuario (arriba a la derecha) › <span class="boton">Mi Perfil</span>.</li>
    <li>Puedes cambiar tu nombre, correo y teléfono.</li>
    <li>Para cambiar la contraseña escribe la <strong>contraseña actual</strong>, la <strong>nueva</strong> y confírmala. Si no quieres cambiarla, deja esos campos en blanco.</li>
    <li>Presiona <span class="boton">Guardar</span>.</li>
</ol>

<h3>Cambiar de empresa</h3>
<p>Si trabajas en más de una empresa, en la barra superior aparece el nombre de la empresa actual: haz clic y elige la otra. Todo lo que veas y registres será de la empresa elegida.</p>

<h3>Cerrar sesión</h3>
<p>Ícono de usuario › <span class="boton">Cerrar sesión</span>. Hazlo siempre al terminar si la computadora es compartida.</p>

<h3>Montos y moneda</h3>
<p>Todos los montos se muestran con la moneda de la empresa (por ejemplo <strong>{{ $currencySymbol }}</strong>). La moneda la configura el administrador en los datos de la empresa.</p>

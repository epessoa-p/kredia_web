<p class="cap-intro">Todo el dinero que entra y sale (préstamos, cobros, ventas, compras y gastos) pasa por una caja. Por eso, lo primero del día es <strong>aperturar la caja</strong> y lo último, <strong>cerrarla</strong>.</p>

<div class="aviso"><strong>Importante:</strong> sin una caja abierta no se puede registrar préstamos, cobros, ventas, compras ni gastos. El sistema muestra el aviso <em>"No hay ninguna caja abierta. Debes aperturar una caja antes de registrar operaciones."</em></div>

<h3>Aperturar la caja (inicio del día)</h3>
<ol class="pasos">
    <li>En la barra superior presiona <span class="boton">Aperturar caja</span>.</li>
    <li>Si eres Gerente, <strong>elige la caja</strong> que vas a abrir (puede ser de otra sucursal). El resto del personal abre directamente su caja asignada.</li>
    <li>Escribe el <strong>monto de apertura</strong>: el efectivo con el que empiezas (cuenta el dinero que hay físicamente).</li>
    <li>Opcional: escribe una nota.</li>
    <li>Presiona <span class="boton">Aperturar</span>. El botón cambia a <span class="boton">Cerrar caja · Sucursal</span>.</li>
</ol>
<div class="nota"><strong>Si no aparece el botón:</strong> tu usuario no tiene una caja asignada. El administrador la asigna en <span class="menu">Cajas</span> (campo <em>Personal asignado</em>).</div>

<h3>Cuánto dinero hay en la caja</h3>
<p>El saldo de la caja es: monto de apertura + ingresos (cobros, ventas) − egresos (préstamos entregados, compras, gastos). Al registrar un préstamo, una compra o un gasto, el sistema muestra el <strong>saldo disponible</strong> y no permite gastar más de lo que hay.</p>

<h3>Registrar un gasto</h3>
<p>Para sacar dinero de la caja por gastos del negocio.</p>
<ol class="pasos">
    <li>Con la caja abierta presiona <span class="boton">Registrar gasto</span> (barra superior).</li>
    <li>Elige el <strong>tipo de gasto</strong>:
        <ul>
            <li><strong>Servicio (básico / externo):</strong> luz, agua, internet, limpieza, etc.</li>
            <li><strong>Pago a personal:</strong> elige además a qué persona se le pagó.</li>
            <li><strong>Otro gasto operativo:</strong> cualquier otro gasto del negocio.</li>
        </ul>
    </li>
    <li>Escribe el <strong>monto</strong>. Debajo verás cómo queda la caja; si el gasto supera el efectivo disponible, no se puede guardar.</li>
    <li>Escribe en <strong>Notas</strong> el detalle (por ejemplo "Factura de luz de octubre") y guarda.</li>
</ol>
<div class="nota"><strong>Nota:</strong> el botón solo aparece si tu cargo tiene permiso para registrar gastos.</div>

<h3>Cerrar la caja (fin del día)</h3>
<ol class="pasos">
    <li>Presiona <span class="boton">Cerrar caja</span> en la barra superior.</li>
    <li>El sistema muestra <strong>"Deberías tener en caja"</strong>: lo que calcula según la apertura y los movimientos del día.</li>
    <li>Cuenta el efectivo y escribe el <strong>monto contado en caja</strong>.</li>
    <li>Si hay diferencia, revisa antes de cerrar. Escribe una nota explicando la diferencia si la hay.</li>
    <li>Presiona <span class="boton">Cerrar caja</span>.</li>
</ol>
<div class="aviso"><strong>Descuadre:</strong> si el monto contado no coincide con el esperado, la diferencia queda registrada como <em>descuadre</em> y se ve en <span class="menu">Movimientos › Cierres de caja</span>. Revisa los movimientos del día antes de cerrar.</div>

<h3>Ver las sesiones de una caja</h3>
<p>En <span class="menu">Cajas</span> › abre una caja para ver su historial: cuándo se abrió y cerró, quién lo hizo, con cuánto se abrió y cerró y los pagos vinculados.</p>
